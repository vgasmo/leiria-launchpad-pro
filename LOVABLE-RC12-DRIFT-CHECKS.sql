  SELECT t.relname,
         string_agg(format(E'      %I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                           CASE WHEN a.atthasdef THEN ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) ELSE '' END,
                           CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END),
                    E',\n' ORDER BY a.attnum) AS body
  FROM t
  JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped
  LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
  GROUP BY t.relname
),
inline_cons AS (   -- PK / UNIQUE / CHECK dentro do CREATE TABLE
  SELECT t.relname,
         string_agg(format(E'      CONSTRAINT %I %s', co.conname, pg_get_constraintdef(co.oid)), E',\n' ORDER BY co.contype, co.conname) AS body
  FROM t JOIN pg_constraint co ON co.conrelid = t.oid AND co.contype IN ('p','u','c')
  GROUP BY t.relname
),
fk AS (            -- FKs depois do CREATE (as tabelas referidas já existem)
  SELECT t.relname,
         string_agg(format(E'    ALTER TABLE public.%I ADD CONSTRAINT %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid)), E'\n' ORDER BY co.conname) AS body
  FROM t JOIN pg_constraint co ON co.conrelid = t.oid AND co.contype = 'f'
  GROUP BY t.relname
),
idx AS (           -- índices que não sustentam constraints
  SELECT t.relname,
         string_agg('    ' || regexp_replace(pg_get_indexdef(i.indexrelid), '^CREATE (UNIQUE )?INDEX ', 'CREATE \1INDEX IF NOT EXISTS ') || ';', E'\n' ORDER BY i.indexrelid::regclass::text) AS body
  FROM t JOIN pg_index i ON i.indrelid = t.oid
  WHERE NOT EXISTS (SELECT 1 FROM pg_constraint co WHERE co.conindid = i.indexrelid)
  GROUP BY t.relname
),
pol AS (
  SELECT t.relname,
         string_agg(format(E'    CREATE POLICY %I ON public.%I AS %s FOR %s TO %s%s%s;', p.polname, t.relname,
                           CASE WHEN p.polpermissive THEN 'PERMISSIVE' ELSE 'RESTRICTIVE' END,
                           CASE p.polcmd WHEN '*' THEN 'ALL' WHEN 'r' THEN 'SELECT' WHEN 'a' THEN 'INSERT' WHEN 'w' THEN 'UPDATE' WHEN 'd' THEN 'DELETE' END,
                           CASE WHEN p.polroles = '{0}' THEN 'public'
                                ELSE (SELECT string_agg(quote_ident(r.rolname), ', ') FROM pg_roles r WHERE r.oid = ANY (p.polroles)) END,
                           CASE WHEN p.polqual IS NOT NULL THEN ' USING (' || pg_get_expr(p.polqual, p.polrelid) || ')' ELSE '' END,
                           CASE WHEN p.polwithcheck IS NOT NULL THEN ' WITH CHECK (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')' ELSE '' END),
                    E'\n' ORDER BY p.polname) AS body
  FROM t JOIN pg_policy p ON p.polrelid = t.oid
  GROUP BY t.relname
),
trg AS (
  SELECT t.relname, string_agg('    ' || pg_get_triggerdef(tr.oid) || ';', E'\n' ORDER BY tr.tgname) AS body
  FROM t JOIN pg_trigger tr ON tr.tgrelid = t.oid AND NOT tr.tgisinternal
  GROUP BY t.relname
),
acl AS (           -- permissões de tabela por papel (anon/authenticated/service_role)
  SELECT t.relname,
         string_agg(format(E'    GRANT %s ON public.%I TO %I;', x.priv, t.relname, x.grantee), E'\n' ORDER BY x.grantee) AS body
  FROM t, LATERAL (
    SELECT r.rolname AS grantee, string_agg(a.privilege_type, ', ' ORDER BY a.privilege_type) AS priv
    FROM pg_class c2, LATERAL aclexplode(c2.relacl) a JOIN pg_roles r ON r.oid = a.grantee
    WHERE c2.oid = t.oid AND r.rolname IN ('anon','authenticated','service_role')
    GROUP BY r.rolname) x
  GROUP BY t.relname
),
table_ddl AS (
  SELECT t.relname AS name, 10 AS grp,
    format(E'DO $rc12$\nBEGIN\n  IF to_regclass(''public.%1$s'') IS NULL THEN\n    CREATE TABLE public.%1$I (\n%2$s\n    );\n%3$s%4$s%5$s%6$s%7$s%8$s%9$s  END IF;\nEND\n$rc12$;\n',
           t.relname,
           cols.body || COALESCE(E',\n' || inline_cons.body, ''),
           CASE WHEN t.relrowsecurity THEN format(E'    ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;\n', t.relname) ELSE '' END,
           CASE WHEN t.relforcerowsecurity THEN format(E'    ALTER TABLE public.%I FORCE ROW LEVEL SECURITY;\n', t.relname) ELSE '' END,
           COALESCE(fk.body || E'\n', ''), COALESCE(idx.body || E'\n', ''), COALESCE(pol.body || E'\n', ''),
           COALESCE(trg.body || E'\n', ''),
           COALESCE(format(E'    REVOKE ALL ON public.%I FROM anon, authenticated, service_role;\n', t.relname) || acl.body || E'\n', '')
    ) AS ddl
  FROM t
  JOIN cols USING (relname)
  LEFT JOIN inline_cons USING (relname) LEFT JOIN fk USING (relname) LEFT JOIN idx USING (relname)
  LEFT JOIN pol USING (relname) LEFT JOIN trg USING (relname) LEFT JOIN acl USING (relname)
),
fn_ddl AS (
  SELECT p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' AS name, 20 AS grp,
         pg_get_functiondef(p.oid) || E';\n' ||
         format('REVOKE ALL ON FUNCTION %s FROM PUBLIC, anon, authenticated, service_role;', p.oid::regprocedure) || E'\n' ||
         COALESCE((SELECT string_agg(format('GRANT EXECUTE ON FUNCTION %s TO %I;', p.oid::regprocedure, r.rolname), E'\n' ORDER BY r.rolname)
                   FROM aclexplode(p.proacl) a JOIN pg_roles r ON r.oid = a.grantee
                   WHERE r.rolname IN ('anon','authenticated','service_role') AND a.privilege_type = 'EXECUTE'), '') || E'\n' ||
         COALESCE((SELECT format('COMMENT ON FUNCTION %s IS %L;', p.oid::regprocedure, d.description) FROM pg_description d WHERE d.objoid = p.oid AND d.classoid = 'pg_proc'::regclass AND d.objsubid = 0), '') || E'\n' AS ddl
  FROM pg_proc p, cfg
  WHERE p.pronamespace = 'public'::regnamespace AND p.proname = ANY (cfg.funcs)
),
all_ddl AS (SELECT name, grp, ddl FROM table_ddl UNION ALL SELECT name, grp, ddl FROM fn_ddl)
SELECT row_number() OVER (ORDER BY grp, name) AS ord, '-- ' || name || E'\n' || ddl AS ddl FROM all_ddl ORDER BY ord;
